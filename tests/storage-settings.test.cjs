const test = require("node:test"), assert = require("node:assert/strict"), fs = require("node:fs"), path = require("node:path"), {JSDOM} = require("jsdom");
const ext = path.join(__dirname, "../_extensions/pyodide-interaktiv");
const libs = process.env.CTM_LIBS_EXTENSION || path.join(__dirname, "../_extensions/ctm-libs");
for (const shared of [true, false]) test("manual-save controls share privacy with CTMStore " + (shared ? "inside feedback settings" : "without AI"), () => {
  const w = new JSDOM('<div id="qpyodide-status-right"></div>', {url: "https://course.invalid/page", runScripts: "outside-only"}).window;
  if (shared) for (const file of ["feedback-core.js", "feedback-dom.js", "ai-feedback.js"]) w.eval(fs.readFileSync(path.join(libs, "feedback", file), "utf8"));
  let enabled = true;
  w.CTMStore = {enabled: () => enabled};
  w.qpyodideLang = "en"; w.qpyodideLocalStorageOptions = {epoch: ""};
  w.qpyodideCellDetails = [{id: "one", code: "print(1)", options: {label: "one"}}];
  for (const file of ["ctm-locale.js", "common.js", "pyodide-interaktiv.js"]) w.eval(fs.readFileSync(path.join(libs, "locales", file), "utf8"));
  w.QP_L = w.CTMLocales.table("pyodide-interaktiv", "en");
  w.localStorage.setItem("qpyodide:code:/page:label:one", "old code");
  for (const file of ["qpyodide-storage.js", "qpyodide-storage-settings.js"]) w.eval(fs.readFileSync(path.join(ext, file), "utf8"));
  const section = w.document.querySelector(".qpyodide-storage-settings-section");
  assert.equal(section.querySelector('input[type="checkbox"]'), null, "privacy toggle belongs to shared page bar");
  assert.equal(section.querySelector(".qpyodide-storage-delete-btn"), null, "course deletion belongs to shared page bar");
  const radios = section.querySelectorAll('input[type="radio"]');
  radios[1].click(); assert.equal(w.qpyodideStorage.isManualMode(), true);
  assert.equal(w.localStorage.getItem("qpyodide:code:/page:label:one"), "old code");
  enabled = false; w.document.dispatchEvent(new w.CustomEvent("ctm:store-enabled"));
  assert.ok([...radios].every(input => input.disabled));
  enabled = true; w.document.dispatchEvent(new w.CustomEvent("ctm:store-enabled"));
  assert.ok([...radios].every(input => !input.disabled));
  w.document.querySelector(".qpyodide-storage-gear").click(); assert.ok(w.document.querySelector("dialog[open]"));
  if (shared) assert.ok(w.document.querySelector("dialog.ai-feedback-settings").contains(section));
  w.close();
});
